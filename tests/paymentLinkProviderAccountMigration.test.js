const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const { collectMigrations } = require('../src/db/migrate')

test('payment link attempts can retain the ITC provider account identity for A/R refunds', async () => {
  const migration = fs.readFileSync(path.resolve(__dirname, '../src/db/migrations/0013_payment_link_provider_account_snapshot.sql'), 'utf8')
  assert.match(migration, /ADD COLUMN provider_account_id uuid/)
  assert.match(migration, /ADD COLUMN provider_account_version integer/)
  assert.match(migration, /payment_link_attempts_provider_account_pair_check/)
  const migrations = await collectMigrations()
  assert.equal(migrations.at(-1).name, '0015_staff_payout_retries.sql')
})

test('provider add-on lifecycle migration generalizes operation identity without rewriting prior rows', async () => {
  const migration = fs.readFileSync(path.resolve(__dirname, '../src/db/migrations/0014_provider_addon_lifecycle.sql'), 'utf8')
  assert.match(migration, /request_payout_attempts_provider_account_pair_check/)
  assert.match(migration, /expense_requests_payout_provider_account_pair_check/)
  assert.match(migration, /payout_provider_account_id/)
  assert.match(migration, /payout_provider_account_version/)
  assert.match(migration, /provider account snapshot can only be set once/)
  assert.match(migration, /provider_callback_inbox_provider_account_pair_check/)
  assert.match(migration, /provider_balance_snapshot_batches_provider_account_pair_check/)
  assert.match(migration, /provider_code ~ '\^\[a-z\]/)
  assert.match(migration, /network_code ~ '\^\[A-Z0-9_\]/)
  assert.doesNotMatch(migration, /UPDATE\s+(payment_link_attempts|request_payout_attempts|provider_callback_inbox|provider_balance_snapshot_batches)/i)
})
